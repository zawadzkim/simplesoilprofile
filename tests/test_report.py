"""Publication tables: LaTeX data rows with provenance, Markdown, horizon summaries."""

import re

from simplesoilprofile import CompartmentRule, Horizon, SoilLibrary, SoilProfile
from simplesoilprofile.report import LIBRARY_COLUMNS, Column, horizon_frame, latex_rows, library_frame, markdown_table
from tests.conftest import material

LIB = SoilLibrary(name="s", materials={m.name: m for m in (material("L1 topsoil", k_sat=104.0), material("L3 leaky", k_sat=0.17, l_mualem=-1.2831))})
PROF = SoilProfile(name="S05", horizons=[
    Horizon(material=LIB["L1 topsoil"], bottom=0.5, rule=CompartmentRule(hcomp=0.02, top_cap=(0.10, 0.01)), key="L1 topsoil"),
    Horizon(material=LIB["L3 leaky"], bottom=0.5, key="L3 leaky"),
    Horizon(material=LIB["L3 leaky"], bottom=2.4, rule=CompartmentRule(hcomp=0.05), key="L3 leaky"),
])


def test_library_frame_columns_and_attrs():
    f = library_frame(LIB)
    assert f.index.name == "material" and f.index.tolist() == ["L1 topsoil", "L3 leaky"]
    assert f.columns.tolist() == [c.label for c in LIBRARY_COLUMNS]
    assert f.attrs["units"]["K_s"] == "cm d-1" and f.attrs["formats"]["alpha"] == "{:.4f}"
    small = library_frame(LIB, [Column("k_sat", "Ks", "cm/d", "{:.2f}"), Column("n", "n", "-")])
    assert small.columns.tolist() == ["Ks", "n"] and small.loc["L3 leaky", "Ks"] == 0.17


def test_latex_rows_are_data_only_with_provenance():
    tex = latex_rows(library_frame(LIB), provenance=["notebook 03-2026-09-06", "commit abc123"])
    lines = tex.strip().splitlines()
    assert lines[0].startswith("% generated by simplesoilprofile") and "data rows only" in lines[0]
    assert lines[1] == "% notebook 03-2026-09-06" and lines[2] == "% commit abc123"
    rows = [line for line in lines if not line.startswith("%")]
    assert len(rows) == 2 and all(line.endswith(r" \\") for line in rows)
    assert rows[0].startswith(r"L1 topsoil & 92 & 5 & 3 & 1.50 & 0.040 & 0.380 & 0.0500 & 1.480 & 0.50 & 104")
    assert "-1.28" in rows[1] and rows[1].split(" & ")[-1] == r"0.17 \\"
    assert r"\begin" not in tex and "&" not in lines[0]


def test_latex_escapes_and_writes(tmp_path):
    lib = SoilLibrary(name="s", materials={"sand_50%": material("sand_50%")})
    path = tmp_path / "soil_rows.tex"
    tex = latex_rows(library_frame(lib), path, index=True)
    assert path.read_text() == tex and r"sand\_50\%" in tex
    no_index = latex_rows(library_frame(lib), index=False)
    assert not re.search(r"^sand", no_index, re.M)


def test_horizon_frame_and_markdown():
    f = horizon_frame(PROF)
    assert f.index.tolist() == [1, 3]  # the absent horizon 2 is left out
    assert f.loc[1, "hcomp_m"] == "0.01/0.02" and f.loc[1, "ncomp"] == 30
    assert f.loc[3, "hcomp_m"] == 0.05 and f.loc[3, "ncomp"] == 38
    assert horizon_frame(PROF, include_absent=True).index.tolist() == [1, 2, 3]
    md = markdown_table(f)
    assert md.splitlines()[0] == "| horizon | material | top_m (m) | bottom_m (m) | thickness_m (m) | hcomp_m (m) | ncomp |"
    assert "| 1 | L1 topsoil | 0.00 | 0.50 | 0.50 | 0.01/0.02 | 30 |" in md
    no_rule = horizon_frame(PROF.with_rule(2, None))
    assert (md.count("\n") == 3 and no_rule.loc[3, "ncomp"] is None) or no_rule.loc[3, "ncomp"] != no_rule.loc[3, "ncomp"]


def test_markdown_library():
    md = markdown_table(library_frame(LIB))
    assert md.startswith("| material | sand (%) | silt (%) | clay (%) | rho_b (g cm-3) |")
    assert "| L3 leaky | 92 | 5 | 3 | 1.50 | 0.040 | 0.380 | 0.0500 | 1.480 | -1.28 | 0.17 |" in md
